import { expect, loginPatientUI, loginStaffUI, signupViaApi, test } from './fixtures'

test('Test 10: access control is enforced by the backend and routes', async ({ page, newPage }) => {
  const p = await signupViaApi(page)
  await loginPatientUI(page, p.email)
  for (const url of ['/api/patients/PAT001/readings', '/api/patients/PAT001/alerts', '/api/patients/PAT001', '/api/alerts', '/api/alerts/pending-by-patient', '/api/notifications']) {
    expect((await page.request.get(url)).status(), url).toBe(403)
  }
  expect((await page.request.post('/api/patients/PAT001/acknowledge')).status()).toBe(403)
  expect((await page.request.post(`/api/patients/${p.patientId}/acknowledge`)).status()).toBe(403)
  await page.goto('/nurse/dashboard')
  await expect(page).toHaveURL(/\/patient\/dashboard/) // redirected to own dashboard

  const nurse = await newPage()
  await loginStaffUI(nurse, 'NUR002', 'nurse')
  expect((await nurse.request.post('/api/simulation/start')).status()).toBe(403)
  expect((await nurse.request.post('/api/simulation/generate-reading', { data: {} })).status()).toBe(403)
  await nurse.goto('/patient/dashboard')
  await expect(nurse).toHaveURL(/\/nurse\/dashboard/)

  const anon = await newPage()
  expect((await anon.request.get('/api/patients/PAT001/readings')).status()).toBe(401)
  await anon.goto('/doctor/dashboard')
  await expect(anon).toHaveURL(/\/$/)
})

